"""Run only against a disposable sample-mode Elliott server."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", default="http://127.0.0.1:8766")
    args = parser.parse_args()
    out = Path("artifacts/elliott-ui")
    out.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": 1440, "height": 1050})
        errors = []
        page.on("pageerror", lambda error: errors.append(str(error)))
        page.goto(args.url)
        expect(page.locator("#mode")).to_have_text("SAMPLE")
        expect(page.locator("#price")).not_to_have_text("—", timeout=20000)
        expect(page.locator("#engine-state")).to_have_text("신규 진입 중단")
        for tf in ("1w", "1d", "4h", "1h"):
            page.locator(f'[data-tf="{tf}"]').click()
            expect(page.locator("#bar-count")).to_contain_text("마감봉만")
        page.locator('[data-tf="4h"]').click()
        page.wait_for_function("() => chartData?.timeframe === '4h'")
        page.locator("#chart-range").select_option("720")
        expect(page.locator("#bar-count")).to_contain_text("720 /")
        page.locator("#chart-zoom-in").click()
        expect(page.locator("#chart-range")).to_have_value("360")
        page.locator("#chart-zoom-out").click()
        expect(page.locator("#chart-range")).to_have_value("720")
        page.locator("#chart-window").fill("0")
        page.locator("#chart-window").dispatch_event("input")
        expect(page.locator("#chart-latest")).to_be_enabled()
        page.locator("#chart-latest").click()
        expect(page.locator("#chart-latest")).to_be_disabled()
        options = page.locator("#chart-count option").evaluate_all("els=>els.map(e=>e.value)")
        if len(options) > 1:
            page.locator("#chart-count").select_option(options[-1])
            expect(page.locator("#chart-count")).to_have_value(options[-1])
            expect(page.locator("#wave-pivots tr")).not_to_have_count(0)
            page.locator("#chart-fit").click()
            expect(page.locator("#chart-caption")).not_to_contain_text("범위 밖")
            page.locator("#chart-count").select_option("auto")
        for selector in ("#show-tail", "#show-levels", "#show-fib", "#show-subwaves"):
            page.locator(selector).check()
        page.locator("#chart").hover()
        expect(page.locator("#chart-ohlc")).to_contain_text("거래량")
        page.locator('[data-tf="30m"]').click()
        expect(page.locator("#chart-warning")).to_contain_text("30분봉 원본이 없습니다")
        expect(page.locator("#wave-status")).to_contain_text("참고 전용")
        expect(page.locator("#bar-count")).to_have_text("0봉")
        page.locator('[data-tf="4h"]').click()
        page.wait_for_function("() => chartData?.timeframe === '4h'")
        page.locator("#chart-range").select_option("360")
        page.locator('[data-view="settings"]').click()
        page.locator('[name="leverage"]').fill("3")
        page.locator('[name="capital"]').fill("1200")
        page.get_by_role("button", name="설정 저장", exact=True).click()
        expect(page.locator("#notice")).to_contain_text("저장했습니다")
        page.reload()
        expect(page.locator("#leverage")).to_have_text("3×")
        page.locator('[data-view="settings"]').click()
        expect(page.locator('[name="capital"]')).to_have_value("1200")
        page.locator('[name="leverage"]').fill("1")
        page.get_by_role("button", name="설정 저장", exact=True).click()
        expect(page.locator("#leverage")).to_have_text("1×")
        page.locator('[data-action="start"]').click()
        expect(page.locator("#engine-state")).to_have_text("자동매매 가동")
        page.locator('[data-action="pause"]').click()
        expect(page.locator("#engine-state")).to_have_text("신규 진입 중단")
        page.locator('[data-action="flatten"]').click()
        expect(page.locator("#confirm")).to_be_visible()
        page.get_by_role("button", name="취소", exact=True).click()
        page.locator('[data-view="journal"]').click()
        expect(page.locator("#journal")).to_contain_text("CONTROL")
        page.locator('[data-view="connect"]').click()
        expect(page.locator('#credentials-form input[name="key"]')).to_be_disabled()
        page.locator('[data-view="validation"]').click()
        page.locator("#backtest").click()
        expect(page.locator("#bt-state")).to_contain_text("검증 완료", timeout=120000)
        expect(page.locator("#bt-bars")).to_have_text("240봉")
        page.locator('[data-view="settings"]').click()
        page.locator('[name="strategy_mode"]').select_option("multi")
        page.get_by_role("button", name="설정 저장", exact=True).click()
        page.wait_for_function("() => latest?.decision?.version === 'ew-multiscenario-2.0'",timeout=60000)
        expect(page.locator("#engine-state")).to_have_text("신규 진입 중단")
        page.locator('[data-view="analysis"]').click()
        expect(page.locator("#scenario-section")).to_be_visible()
        page.locator('[data-tf="30m"]').click()
        page.wait_for_function("() => chartData?.timeframe === '30m' && chartData.candles.length > 0")
        expect(page.locator("#wave-status")).to_contain_text("하위 확인 전용")
        page.locator('[data-tf="4h"]').click()
        page.locator('[data-view="validation"]').click()
        page.locator("#compare-strategies").click()
        comparison_count = 5 if page.evaluate("() => latest.limits?.strategy_modes?.includes('active')") else 3
        expect(page.locator("#comparison-results tbody tr")).to_have_count(comparison_count,timeout=300000)
        expect(page.locator("#bt-state")).to_contain_text("판정 불가")
        for width, height in ((1440, 1050), (390, 844), (360, 800)):
            page.set_viewport_size({"width": width, "height": height})
            for view in ("analysis", "journal", "settings", "connect", "validation"):
                page.locator(f'[data-view="{view}"]').click()
                page.screenshot(path=str(out / f"{view}-{width}.png"), full_page=True)
                assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), (view, width, "page overflow")
                overflow = page.locator("button:visible").evaluate_all("els=>els.filter(e=>e.scrollWidth>e.clientWidth+2).map(e=>e.textContent)")
                assert not overflow, (view, width, overflow)
        page.locator('[data-view="analysis"]').click()
        pixels = page.locator("#chart").evaluate("c=>{let n=0,d=c.getContext('2d').getImageData(0,0,c.width,c.height).data;for(let i=3;i<d.length;i+=4)if(d[i])n++;return n;}")
        assert pixels > 1000, pixels
        response = page.request.get(args.url + "/rules.md")
        assert response.ok and "엘리엇 파동" in response.text()
        page.locator('[data-action="flatten"]').click()
        page.get_by_role("button", name="확인", exact=True).click()
        expect(page.locator("#position")).to_have_text("없음")
        assert not errors, errors
        browser.close()
        print(json.dumps({"ok": True, "viewports": [1440, 390, 360], "views": 5, "nonblank_pixels": pixels,
                          "checks": ["settings persistence", "four execution timeframes", "reference-only 30m empty state", "multi profile and 30m confirmation", "strategy comparison", "long history", "zoom and pan", "candidate selection", "wave evidence", "overlays and crosshair", "start/pause", "confirmation cancellation", "journal", "key gating", "causal replay", "rules download", "no page overflow", "no JS errors"]}))


if __name__ == "__main__":
    main()
